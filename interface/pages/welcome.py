from PySide6.QtCore import Qt, Signal
from PySide6.QtWidgets import QWidget, QVBoxLayout, QHBoxLayout, QLabel, QPushButton, QFrame
from interface.widgets.branding import WelcomeIllustration

class WelcomePage(QWidget):
    create_case = Signal()
    quick_triage = Signal()
    resume_triage = Signal()
    def __init__(self):
        super().__init__()
        layout = QVBoxLayout(self)
        layout.setContentsMargins(24,24,24,16)
        layout.addStretch(2)
        card = QFrame()
        card.setObjectName('card')
        card.setMaximumWidth(620)
        inner = QVBoxLayout(card)
        inner.setContentsMargins(35,35,35,35)
        inner.setSpacing(18)
        for text, name in [('DIGITAL FORENSIC TRIAGE','eyebrow'),('T3RRA','hero'),('Triage Forensic Collector','subtitle'),('A guided workflow for digital evidence triage.','description')]:
            label = QLabel(text)
            label.setObjectName(name)
            label.setAlignment(Qt.AlignmentFlag.AlignCenter)
            label.setWordWrap(True)
            inner.addWidget(label)
        create = QPushButton('Create Case')
        create.setObjectName('primary')
        create.setMinimumHeight(48)
        create.clicked.connect(self.create_case.emit)
        inner.addWidget(create)
        quick = QPushButton('Quick Triage')
        quick.setObjectName('secondary')
        quick.setMinimumHeight(48)
        quick.clicked.connect(self.quick_triage.emit)
        inner.addWidget(quick)
        self.resume_button = QPushButton('Resume saved triage…')
        self.resume_button.clicked.connect(self.resume_triage.emit)
        inner.addWidget(self.resume_button)
        self.recovery_status = QLabel()
        self.recovery_status.setTextFormat(Qt.TextFormat.PlainText)
        self.recovery_status.setWordWrap(True)
        inner.addWidget(self.recovery_status)
        center = QHBoxLayout()
        center.setSpacing(20)
        center.addStretch()
        self.illustration = WelcomeIllustration()
        center.addWidget(self.illustration, 2)
        center.addWidget(card, 3)
        center.addStretch()
        layout.addLayout(center)
        layout.addStretch(3)
        credit = QLabel('Developed by Gersi Hajrullahi')
        credit.setObjectName('credit')
        credit.setAlignment(Qt.AlignmentFlag.AlignCenter)
        layout.addWidget(credit)
